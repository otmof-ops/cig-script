// Mirrors bench/compute/fib.cig: calls, recursive Fibonacci.
// black_box: the size is not a constant the compiler can fold the work on.
use std::hint::black_box;

fn fib(n: i64) -> i64 {
    if n < 2 {
        return n;
    }
    fib(n - 1) + fib(n - 2)
}

fn main() {
    println!("{}", fib(black_box(25)));
}
